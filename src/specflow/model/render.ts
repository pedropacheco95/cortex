/** `specflow/INDEX.md` and the `--json` form of the model (schema S12.3, S12.5). */
import { type Model, type ModelSpec, counts } from './model.js';

function specLines(spec: ModelSpec): string[] {
  const lines = [`- spec **${spec.id}** (\`${spec.file}\`)`];
  for (const c of spec.criteria) {
    lines.push(`  - **${c.id}** ${c.title}${c.unverified ? ' · unverified' : ''}`);
    for (const t of c.tests) lines.push(`    - test: \`${t.file}\` › ${t.name}${t.skipped ? ' (skipped)' : ''}`);
  }
  return lines;
}

export function renderIndex(model: Model): string {
  const n = counts(model);
  const out: string[] = [
    '# Specs index',
    '',
    'GENERATED by `cortex specs index`. Never edit by hand.',
    '',
    `Promises: ${n.promises} · specs: ${n.specs} · criteria: ${n.criteria} · tagged: ${n.tagged} · unverified: ${n.unverified}`,
    `Untagged tests: ${n.untagged}`,
    '',
    '## Promises',
    '',
  ];
  for (const p of model.promises) {
    out.push(p.business ? `### ${p.file}` : `### ${p.id}: ${p.title}`, '');
    if (!p.business) out.push(`\`${p.file}\``, '');
    const own = model.specs.filter((s) => s.promise === p.file);
    if (own.length > 0) out.push(...own.flatMap(specLines), '');
  }
  const section = (title: string, lines: string[]): void => {
    out.push(title, '');
    if (lines.length > 0) out.push(...lines, '');
  };
  section('## Specs without a promise', model.specs.filter((s) => s.promise === '').flatMap(specLines));
  section(
    '## Specs without criterion ids',
    model.specs.filter((s) => s.missingIds).map((s) => `- **${s.id}** (\`${s.file}\`)`),
  );
  section('## Constants', model.constants.map((c) => `- \`${c.name}\` = \`${c.value}\` · \`${c.file}\``));
  const perFile = new Map<string, number>();
  for (const t of model.untagged) perFile.set(t.file, (perFile.get(t.file) ?? 0) + 1);
  section('## Untagged tests', [...perFile].map(([file, count]) => `- \`${file}\`: ${count}`));
  section(
    '## Tags naming no criterion',
    model.orphanTags.map((t) => `- **${t.id}** \`${t.file}\` › ${t.name}`),
  );
  section('## Retired', model.retired.map((r) => `- **${r.id}** (\`${r.file}\`)`));
  return `${out.join('\n').trimEnd()}\n`;
}

export function modelJson(model: Model): unknown {
  return {
    counts: counts(model),
    promises: model.promises.map(({ id, title, file }) => ({ id, title, file })),
    specs: model.specs.map((s) => ({
      id: s.id,
      file: s.file,
      status: s.status,
      serves: s.serves,
      criteria: s.criteria.map(({ id, title, unverified, tests }) => ({ id, title, unverified, tests })),
    })),
    constants: model.constants,
    untagged: model.untagged.map(({ file, name, line }) => ({ file, name, line })),
    orphanTags: model.orphanTags.map(({ id, file, name, line }) => ({ id, file, name, line })),
    retired: model.retired.map(({ id, file }) => ({ id, file })),
  };
}
