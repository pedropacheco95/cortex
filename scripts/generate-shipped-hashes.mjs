#!/usr/bin/env node
/**
 * One-off generator for `src/store/migrate/shipped-hashes.ts` (`core-cli.sync`
 * Rule 27): the hash of every distinct version of each 3.x bundle in the history
 * of main up to the last commit before Round 2. The list is frozen, because
 * every copy 4.0 writes has a marker, so this runs again only to audit it.
 */
import { execFileSync } from 'child_process';
import { createHash } from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LAST_3X_COMMIT = '88895ca';
const KEPT = ['cortex-register-tasks', 'verification-before-completion'];
const RETIRED = /^(_conventions|cortex-archive-ingest|cortex-extract-insight|cortex-ingest|cortex-loop|cortex-loop-.+|cortex-pulse-.+|specflow-(brainstorm|bugs|change-router|deep-onboard|develop|entry|ingest|intent-reconcile|lint|new-project|onboard-codebase|plan|receive-review|request-review|spec-editor|tests|viewer))$/;

const git = (args, encoding = 'utf8') => execFileSync('git', args, { cwd: REPO, encoding, maxBuffer: 1 << 28 });

/** `hashDirectoryContent` over a git tree: path, NUL, bytes, NUL, in sorted path order. */
function treeHash(commit, name) {
  const prefix = `skills/${name}/`;
  const files = git(['ls-tree', '-r', '--name-only', commit, '--', prefix]).split('\n').filter(Boolean).map((f) => f.slice(prefix.length)).sort();
  if (files.length === 0) return null;
  const hash = createHash('sha256');
  for (const f of files) {
    hash.update(f);
    hash.update('\0');
    hash.update(git(['show', `${commit}:${prefix}${f}`], 'buffer'));
    hash.update('\0');
  }
  return hash.digest('hex');
}

const names = [...new Set(git(['log', '--format=', '--name-only', '--full-history', LAST_3X_COMMIT, '--', 'skills']).split('\n').map((l) => /^skills\/([^/]+)\//.exec(l)?.[1]).filter(Boolean))]
  .filter((n) => KEPT.includes(n) || RETIRED.test(n))
  .sort();

const table = {};
for (const name of names) {
  const commits = git(['log', '--format=%H', '--full-history', LAST_3X_COMMIT, '--', `skills/${name}`]).split('\n').filter(Boolean);
  table[name] = [...new Set(commits.map((c) => treeHash(c, name)).filter(Boolean))].sort();
}

const body = names.map((n) => `  '${n}': [\n${table[n].map((h) => `    '${h}',`).join('\n')}\n  ],`).join('\n');
fs.writeFileSync(path.join(REPO, 'src/store/migrate/shipped-hashes.ts'), `/**
 * Generated by scripts/generate-shipped-hashes.mjs; do not edit. Every distinct
 * version of each 3.x bundle in the history of main up to ${LAST_3X_COMMIT}
 * (\`core-cli.sync\` Rule 27), hashed as \`hashDirectoryContent\` hashes it.
 */
export const SHIPPED_3X_HASHES: Readonly<Record<string, readonly string[]>> = {
${body}
};
`);
console.log(`${names.length} bundles, ${Object.values(table).flat().length} hashes`);
